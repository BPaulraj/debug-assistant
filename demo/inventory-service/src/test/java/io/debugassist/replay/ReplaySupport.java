import java.util.Set;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Generated by debug-agent (regenerated on every "replay"; do not edit).
 * Loads recorded JSON fixtures, answers mocks with recorded values and compares results with the recording.
 */
public final class ReplaySupport {

    private static final ObjectMapper MAPPER = createMapper();

    private final Class<?> testClass;

    public ReplaySupport(Class<?> testClass) {
        this.testClass = testClass;
    }

    /** Reads a recorded value (an argument) as the given type. */
    @SuppressWarnings("unchecked")
    public <T> T load(String fixture, Class<T> type) {
        return (T) toJava(clean(read(fixture)), MAPPER.constructType(wrap(type)));
    }

    /** A Mockito answer that returns / throws what the real collaborator did, in the recorded order. */
    public Answer<Object> answers(String fixture) {
        final JsonNode outcomes = read(fixture);
        final AtomicInteger next = new AtomicInteger();
        return invocation -> {
            int i = Math.min(next.getAndIncrement(), outcomes.size() - 1);
            JsonNode outcome = outcomes.get(i);
            if (outcome.has("throws")) {
                throw exception(outcome.get("throws").asText(), outcome.path("message").isNull()
                        ? null : outcome.path("message").asText(null));
            }
            if (outcome.has("void")) {
                return null;
            }
            Type returnType = invocation.getMethod().getGenericReturnType();
            return toJava(clean(outcome.get("returns")), MAPPER.getTypeFactory().constructType(returnType));
        };
    }

    /** Compares a value with the recorded JSON. Values the recorder summarised (depth/size limits, masked) are skipped. */
    public void assertMatches(String fixture, Object actual) {
        JsonNode expected = read(fixture);
        JsonNode actualTree = MAPPER.valueToTree(actual);
        List<String> diffs = new ArrayList<>();
        compare("$", expected, actualTree, diffs);
        if (!diffs.isEmpty()) {
            StringBuilder msg = new StringBuilder("Result differs from the recording (" + fixture + "):");
            for (String d : diffs) {
                msg.append("\n  ").append(d);
            }
            msg.append("\nactual: ").append(actualTree);
            throw new AssertionError(msg.toString());
        }
    }

    /** Calls a private method of the class under test. */
    public Object invokePrivate(Object target, Class<?> type, String name, Class<?>[] types, Object... args) throws Throwable {
        Method m = type.getDeclaredMethod(name, types);
        m.setAccessible(true);
        try {
            return m.invoke(target, args);
        } catch (InvocationTargetException e) {
            throw e.getCause();
        }
    }

    // ------------------------------------------------------------------ internals

    private static ObjectMapper createMapper() {
        ObjectMapper m = new ObjectMapper();
        m.findAndRegisterModules();
        m.setVisibility(PropertyAccessor.GETTER, JsonAutoDetect.Visibility.NONE);
        m.setVisibility(PropertyAccessor.IS_GETTER, JsonAutoDetect.Visibility.NONE);
        m.setVisibility(PropertyAccessor.SETTER, JsonAutoDetect.Visibility.NONE);
        m.setVisibility(PropertyAccessor.FIELD, JsonAutoDetect.Visibility.ANY);
        m.configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
        m.configure(DeserializationFeature.USE_BIG_DECIMAL_FOR_FLOATS, true);
        m.configure(SerializationFeature.FAIL_ON_EMPTY_BEANS, false);
        m.configure(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS, false);
        // The recorder writes java.util.Date as epoch millis and java.time values as ISO strings.
        m.registerModule(new SimpleModule().addSerializer(Date.class, new DateSerializer(true, null)));
        return m;
    }

    private JsonNode read(String fixture) {
        String path = "/debug-replay/" + testClass.getSimpleName() + "/" + fixture;
        try (InputStream in = testClass.getResourceAsStream(path)) {
            if (in == null) {
                throw new IllegalStateException("fixture not found on the test classpath: " + path);
            }
            return MAPPER.readTree(in);
        } catch (IOException e) {
            throw new IllegalStateException("cannot read fixture " + path, e);
        }
    }

    private Object toJava(JsonNode node, JavaType type) {
        if (node == null || node.isNull()) {
            return type.getRawClass() == Optional.class ? Optional.empty() : null;
        }
        if (node.isObject() && node.has("@type")) {
            try {
                Class<?> recorded = Class.forName(node.get("@type").asText(), false, testClass.getClassLoader());
                if (type.getRawClass().isAssignableFrom(recorded) && type.getRawClass() != recorded) {
                    type = MAPPER.constructType(recorded);
                }
            } catch (ClassNotFoundException ignored) {
                // fall back to the declared type
            }
        }
        Class<?> raw = type.getRawClass();
        if (raw == Optional.class) {
            return Optional.ofNullable(toJava(node, type.containedTypeOrUnknown(0)));
        }
        if (node.isArray() && (raw == Object.class || Collection.class.isAssignableFrom(raw)) && hasTypedElements(node)) {
            Collection<Object> out = Set.class.isAssignableFrom(raw) ? new LinkedHashSet<>() : new ArrayList<>();
            JavaType element = type.getContentType() != null ? type.getContentType() : MAPPER.constructType(Object.class);
            for (JsonNode item : node) {
                out.add(toJava(item, element));
            }
            return out;
        }
        return MAPPER.convertValue(node, type);
    }

    private static boolean hasTypedElements(JsonNode array) {
        for (JsonNode item : array) {
            if (item.isObject() && item.has("@type")) {
                return true;
            }
        }
        return false;
    }

    /** Replaces recorder placeholders ("<max depth>", "<cycle>", "<3 more items>", "****") so they deserialize. */
    private static JsonNode clean(JsonNode node) {
        if (node == null) {
            return null;
        }
        if (node.isObject()) {
            ObjectNode copy = MAPPER.createObjectNode();
            Iterator<Map.Entry<String, JsonNode>> it = node.fields();
            while (it.hasNext()) {
                Map.Entry<String, JsonNode> e = it.next();
                if (!e.getKey().startsWith("<")) {
                    copy.set(e.getKey(), isPlaceholder(e.getValue()) ? MAPPER.nullNode() : clean(e.getValue()));
                }
            }
            return copy;
        }
        if (node.isArray()) {
            ArrayNode copy = MAPPER.createArrayNode();
            for (JsonNode item : node) {
                if (!isPlaceholder(item)) {
                    copy.add(clean(item));
                }
            }
            return copy;
        }
        return node;
    }

    private static boolean isPlaceholder(JsonNode n) {
        if (!n.isTextual()) {
            return false;
        }
        String s = n.asText();
        return (s.startsWith("<") && s.endsWith(">") && s.length() > 2) || s.equals("****");
    }

    private static void compare(String path, JsonNode expected, JsonNode actual, List<String> diffs) {
        if (expected == null || expected.isMissingNode()) {
            return;
        }
        if (isPlaceholder(expected) || expected.isTextual() && expected.asText().contains("...<")) {
            return; // the recorder did not keep the full value
        }
        if (actual == null || actual.isMissingNode()) {
            diffs.add(path + ": expected " + expected + " but was missing");
            return;
        }
        if (expected.isNull() || actual.isNull()) {
            if (expected.isNull() != actual.isNull()) {
                diffs.add(path + ": expected " + expected + " but was " + actual);
            }
            return;
        }
        if (expected.isNumber() && actual.isNumber()) {
            if (new BigDecimal(expected.asText()).compareTo(new BigDecimal(actual.asText())) != 0) {
                diffs.add(path + ": expected " + expected.asText() + " but was " + actual.asText());
            }
            return;
        }
        if (expected.isObject() && actual.isObject()) {
            Iterator<Map.Entry<String, JsonNode>> it = expected.fields();
            while (it.hasNext()) {
                Map.Entry<String, JsonNode> e = it.next();
                if (!e.getKey().startsWith("@") && !e.getKey().startsWith("<")) {
                    compare(path + "." + e.getKey(), e.getValue(), actual.get(e.getKey()), diffs);
                }
            }
            return;
        }
        if (expected.isArray() && actual.isArray()) {
            int n = 0;
            for (JsonNode item : expected) {
                if (isPlaceholder(item)) {
                    return; // "<n more items>": the rest was not recorded
                }
                compare(path + "[" + n + "]", item, actual.get(n), diffs);
                n++;
            }
            if (actual.size() != n) {
                diffs.add(path + ": expected " + n + " items but was " + actual.size());
            }
            return;
        }
        if (expected.isTextual() && (actual.isObject() || actual.isArray())) {
            return; // a framework object the recorder summarised with toString()
        }
        if (!expected.asText().equals(actual.asText()) && !sameTemporal(expected.asText(), actual.asText())) {
            diffs.add(path + ": expected " + expected + " but was " + actual);
        }
    }

    /** "2024-01-02T10:00:00.120" and "2024-01-02T10:00:00.12" are the same value written differently. */
    private static boolean sameTemporal(String a, String b) {
        List<java.util.function.Function<String, Object>> parsers = java.util.Arrays.asList(
                java.time.OffsetDateTime::parse, java.time.ZonedDateTime::parse, java.time.Instant::parse,
                java.time.LocalDateTime::parse, java.time.LocalDate::parse, java.time.LocalTime::parse,
                java.time.OffsetTime::parse);
        for (java.util.function.Function<String, Object> p : parsers) {
            try {
                return p.apply(a).equals(p.apply(b));
            } catch (RuntimeException notThisFormat) {
                // try the next one
            }
        }
        return false;
    }

    private static Class<?> wrap(Class<?> c) {
        if (!c.isPrimitive()) return c;
        if (c == int.class) return Integer.class;
        if (c == long.class) return Long.class;
        if (c == boolean.class) return Boolean.class;
        if (c == double.class) return Double.class;
        if (c == float.class) return Float.class;
        if (c == short.class) return Short.class;
        if (c == byte.class) return Byte.class;
        return Character.class;
    }

    private static Throwable exception(String type, String message) {
        try {
            Class<?> c = Class.forName(type);
            try {
                Constructor<?> withMessage = c.getConstructor(String.class);
                return (Throwable) withMessage.newInstance(message);
            } catch (NoSuchMethodException e) {
                return (Throwable) c.getConstructor().newInstance();
            }
        } catch (Exception e) {
            return new RuntimeException(type + ": " + message);
        }
    }
}
